export interface WordEntry {
  word: string;
  tags: string[];
}

export const WORDS: WordEntry[] = RAW.trim()
  .split('\n')
  .map((line) => {
    const [word, tags] = line.split(':');
    return { word: word.trim(), tags: tags.split(',').map((t) => t.trim()).filter(Boolean) };
  });

const wordSet = new Set(WORDS.map((w) => w.word));
/** 힌트로 쓸 수 있는 태그 (보드 단어와 겹치는 태그는 제외) */
export const CLUE_TAGS = [...new Set(WORDS.flatMap((w) => w.tags))].filter((t) => !wordSet.has(t));

export const tagsOf = (word: string): string[] => WORDS.find((w) => w.word === word)?.tags.filter((t) => !wordSet.has(t)) ?? [];

/** 주제 묶음: 태그로 골라낸 단어들 (단어가 충분해야 보드가 만들어짐) */
export const PACKS: Record<string, { label: string; tags: string[] | null }> = {
  all: { label: '모든 단어', tags: null },
  nature: { label: '자연·동물', tags: ['동물', '새', '물고기', '곤충', '바다', '하늘', '숲', '산', '꽃', '나무', '날씨', '강', '우주'] },
  daily: { label: '일상·음식', tags: ['음식', '간식', '과일', '채소', '음료', '부엌', '집', '옷', '학생', '탈것', '도시'] },
  fantasy: { label: '모험·상상', tags: ['동화', '마법', '왕', '성', '전쟁', '무기', '비밀', '우주', '무서운', '영화', '보석'] },
};

export function packWords(pack: string): string[] {
  const p = PACKS[pack] ?? PACKS.all;
  return WORDS.filter((w) => !p.tags || w.tags.some((t) => p.tags!.includes(t))).map((w) => w.word);
}
